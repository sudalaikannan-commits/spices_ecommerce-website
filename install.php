    <?php endforeach; ?>
    <form method="post" autocomplete="off">
      <div class="grid-2">
        <label>Admin name<input type="text" name="admin_name" value="<?= e($_POST['admin_name'] ?? 'Store Administrator') ?>" required></label>
        <label>Admin email<input type="email" name="admin_email" value="<?= e($adminEmail) ?>" required></label>
        <label>Admin password<input type="password" name="admin_password" placeholder="min 8 characters" required></label>
        <label>Database name<input type="text" name="db_name" value="<?= e($dbName ?? DB_NAME) ?>" required></label>
        <label>Database host<input type="text" name="db_host" value="<?= e(DB_HOST) ?>" required></label>
        <label>Database user<input type="text" name="db_user" value="<?= e(DB_USER) ?>" required></label>
