<?php
/**
 * Samand Co. — one-time web installer.
 * Creates the database, tables, seed data and the first admin account.
 * Delete this file after installation.
 */

declare(strict_types=1);

require_once __DIR__ . '/config/db.php';
require_once __DIR__ . '/config/helpers.php';

$errors = [];
$done = false;
$created = false;

$adminEmail = 'admin@samandco.com';
$adminPass = 'Admin@123';

$server = $_SERVER['SERVER_NAME'] ?? 'localhost';
$scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
$selfDir = rtrim(str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? '/')), '/');

if (is_post()) {
    $adminName = trim((string) ($_POST['admin_name'] ?? 'Store Administrator'));
    $adminEmail = trim((string) ($_POST['admin_email'] ?? $adminEmail));
    $adminPass = (string) ($_POST['admin_password'] ?? '');
    $dbName = preg_replace('/[^a-zA-Z0-9_]/', '', (string) ($_POST['db_name'] ?? DB_NAME)) ?: 'samand_co';
    $dbUser = trim((string) ($_POST['db_user'] ?? DB_USER));
    $dbPass = (string) ($_POST['db_pass'] ?? DB_PASS);
    $dbHost = trim((string) ($_POST['db_host'] ?? DB_HOST));

    if (!filter_var($adminEmail, FILTER_VALIDATE_EMAIL)) {
        $errors[] = 'Admin email is not valid.';
    }
    if (strlen($adminPass) < 8) {
        $errors[] = 'Admin password must be at least 8 characters.';
    }

    if (!$errors) {
        try {
            $root = new PDO(
                sprintf('mysql:host=%s;port=%s;charset=utf8mb4', $dbHost, DB_PORT),
                $dbUser,
                $dbPass,
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
            );
            $root->exec("CREATE DATABASE IF NOT EXISTS `{$dbName}` DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");

            $pdo = new PDO(
                sprintf('mysql:host=%s;port=%s;dbname=%s;charset=utf8mb4', $dbHost, DB_PORT, $dbName),
                $dbUser,
                $dbPass,
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
            );

            $sql = file_get_contents(APP_ROOT . '/sql/schema.sql');
            if ($sql === false) {
                throw new RuntimeException('Could not read sql/schema.sql');
            }

            /* Strip CREATE DATABASE / USE (we already connected to the right DB). */
            $sql = preg_replace('/^\s*(?:CREATE\s+DATABASE|USE)\s+[^;]*;\s*$/mi', '', $sql) ?? $sql;

            $executed = 0;
            foreach (explode(';', $sql) as $piece) {
                /* Remove comment lines, then skip anything left that is not SQL. */
                $statement = trim((string) preg_replace('/^\s*--.*$/m', '', $piece));
                if ($statement === '' || !preg_match('/^\s*(CREATE|INSERT|UPDATE|ALTER|DROP|SET)/i', $statement)) {
                    continue;
                }
                $pdo->exec($statement);
                $executed++;
            }
            if ($executed < 20) {
                throw new RuntimeException('Schema did not apply cleanly (' . $executed . ' statements). Check sql/schema.sql.');
            }

            $stmt = $pdo->prepare('SELECT COUNT(*) FROM admins');
            $stmt->execute();
            if ((int) $stmt->fetchColumn() === 0) {
                $stmt = $pdo->prepare('INSERT INTO admins (name, email, password_hash, role, status) VALUES (?,?,?,?,?)');
                $stmt->execute([$adminName, $adminEmail, password_hash($adminPass, PASSWORD_DEFAULT), 'superadmin', 'active']);
            }

            /* Persist the connection details so config/db.php picks them up. */
            $local = "<?php\n"
                . "/* Generated by install.php — keep this file out of version control. */\n"
                . "define('DB_HOST', " . var_export($dbHost, true) . ");\n"
                . "define('DB_PORT', " . var_export((string) DB_PORT, true) . ");\n"
                . "define('DB_NAME', " . var_export($dbName, true) . ");\n"
                . "define('DB_USER', " . var_export($dbUser, true) . ");\n"
                . "define('DB_PASS', " . var_export($dbPass, true) . ");\n";
            file_put_contents(APP_ROOT . '/config/local.php', $local);

            $created = true;
            $done = true;
        } catch (Throwable $e) {
            $errors[] = 'Install failed: ' . $e->getMessage();
        }
    }
}
